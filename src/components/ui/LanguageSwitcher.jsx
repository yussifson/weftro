export function LanguageSwitcher({ currentLanguage, onChange, className }) {
  const [lang, setLang] = useState(currentLanguage || 'en');

  useEffect(() => {
    if (currentLanguage) {
      setLang(currentLanguage);
    } else {
      // Check for Google Translate cookie to initialize correctly
      const match = document.cookie.match(/(^|;) ?googtrans=([^;]*)(;|$)/);
      if (match) {
        const parts = match[2].split('/');
        if (parts.length > 2) {
          setLang(parts[2]);
        }
      }
    }
  }, [currentLanguage]);

  const triggerGoogleTranslate = (langCode) => {
    // Save to Google's translate cookie directly so it persists reliably
    document.cookie = `googtrans=/en/${langCode}; path=/; domain=${window.location.hostname}`;
    document.cookie = `googtrans=/en/${langCode}; path=/`;
    
    // Find the hidden Google Translate dropdown and trigger a change
    const googleSelect = document.querySelector('.goog-te-combo');
    if (googleSelect) {
      googleSelect.value = langCode;
      googleSelect.dispatchEvent(new Event('change'));
    } else {
      // If widget not fully loaded yet, reload the page to apply cookie
      window.location.reload();
    }
  };

  const handleLanguageChange = async (val) => {
    setLang(val);
    triggerGoogleTranslate(val);
    if (onChange) onChange(val);
    
    // Persist language across devices in user metadata
    try {
      const { supabase } = await import('@/api/supabaseClient');
      const { data: { session } } = await supabase.auth.getSession();
      if (session?.user) {
        await supabase.auth.updateUser({
          data: { language: val }
        });
      }
    } catch (e) {
      console.warn('Failed to persist language preference:', e);
    }
  };

  return (
    <div className="notranslate">
      <Select value={lang} onValueChange={handleLanguageChange}>
        <SelectTrigger className={className || "h-11 bg-[#006065] text-white border border-white/10 hover:bg-white/10 transition-colors"}>
          <div className="flex items-center gap-2">
            <Globe className="w-4 h-4 text-white/70" />
            <span className="truncate"><SelectValue /></span>
          </div>
        </SelectTrigger>
        <SelectContent className="max-h-[300px] notranslate bg-[#006065] text-white border border-white/10 shadow-xl">
          {GOOGLE_LANGUAGES.map(l => (
            <SelectItem key={l.code} value={l.code} className="text-white hover:bg-[#00beac] hover:text-[#00beac] focus:bg-[#00beac] focus:text-[#00beac] data-[highlighted]:bg-[#00beac] data-[highlighted]:text-[#00beac] cursor-pointer font-medium">{l.name}</SelectItem>
          ))}
        </SelectContent>
      </Select>
    </div>
  );
}
